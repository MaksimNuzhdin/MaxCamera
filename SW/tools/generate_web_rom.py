#!/usr/bin/env python3
"""Embed the local console assets in R5 so page loading does not wait on Linux."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    output = ['/* Generated by tools/generate_web_rom.py; do not edit. */']
    for name, mime, symbol in [('index.html','text/html; charset=utf-8','index'),
                               ('style.css','text/css','style'),
                               ('app.js','text/javascript','app')]:
        body = (ROOT/'ai/web'/name).read_bytes()
        header = (f'HTTP/1.0 200 OK\r\nContent-Type: {mime}\r\nContent-Length: {len(body)}\r\n'
                  "Connection: close\r\nCache-Control: no-store\r\nX-Content-Type-Options: nosniff\r\n"
                  "Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self'; "
                  "img-src 'self' blob:; frame-ancestors 'none'; base-uri 'none'; form-action 'self'\r\n\r\n").encode()
        data = header+body
        output.append(f'static const unsigned char web_{symbol}[] = {{')
        output.extend(','.join(str(v) for v in data[i:i+24])+',' for i in range(0,len(data),24))
        output.append('};')
    target = ROOT/'gige/GigeWebRom.h'
    content = '\n'.join(output)+'\n'
    if not target.exists() or target.read_text() != content:
        target.write_text(content)

if __name__ == '__main__':
    main()
